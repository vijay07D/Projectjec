// Helper to generate polygon rings around center coordinate
const generatePolygonRing = (
  lat: number,
  lng: number,
  radiusLat = 0.015,
  radiusLng = 0.018
): [number, number][] => {
  const points: [number, number][] = [];
  const count = 7;
  for (let i = 0; i < count; i++) {
    const angle = (i * 2 * Math.PI) / count;
    // slight irregular jitter for realistic administrative polygon boundaries
    const jitter = 0.88 + ((i % 3) * 0.09);
    const pLat = Number((lat + Math.sin(angle) * radiusLat * jitter).toFixed(5));
    const pLng = Number((lng + Math.cos(angle) * radiusLng * jitter).toFixed(5));
    points.push([pLat, pLng]);
  }
  // Close the polygon
  points.push(points[0]);
  return points;
};

